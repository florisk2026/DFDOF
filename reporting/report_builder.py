def _p5_anomaly_detail(pdf: _PDF, state: State) -> None:
    """Render a per-file breakdown of P5 anomaly checks on a new page."""
    p5_anomalies: list[dict] = (
        state.phase_outputs
        .get("p5_normalisation_and_anomaly_checking", {})
        .get("derived_anomalies", [])
    )
    if not p5_anomalies:
        return

    # Row-level check keys whose values are lists of row indices
    _ROW_CHECKS = {
        "timestamp_regression", "timestamp_gap", "zero_coordinate",
        "missing_gps", "coordinate_jump", "altitude_negative",
        "altitude_spike", "motor_airborne_off", "gps_poor_fix",
        "gps_accuracy_poor", "quaternion_invalid", "attitude_out_of_bounds",
        "battery_cell_voltage_out_of_range", "battery_cell_imbalance",
        "battery_temperature_out_of_range", "motor_on_empty_battery",
    }
    # Column-level check keys whose values are lists of column names
    _COL_CHECKS = {"contains_no_value", "contains_constant_value"}

    # Group by evidence_category, preserving SOURCE_IDENTIFICATION_TYPES order
    from config import SOURCE_IDENTIFICATION_TYPES
    cat_order = ["databases", "drone_logs", "flight_logs", "flight_records",
                 "account_data", "images", "videos"]
    by_cat: dict[str, list[dict]] = {}
    for a in p5_anomalies:
        cat = a.get("evidence_category") or "other"
        by_cat.setdefault(cat, []).append(a)

    # Build sha256 → original filename lookup from P3+P4 artefacts so image/video
    # entries can show the real media filename instead of the _exif.json sidecar name.
    p3_arts = state.phase_outputs.get("p3_artefact_extraction", {}).get("extracted_artefacts", [])
    p4_arts = state.phase_outputs.get("p4_decision_and_orchestration", {}).get("decision_and_orchestration_artefacts", [])
    _sha_to_fname: dict[str, str] = {
        a["sha256"]: Path(str(a["stored_path"])).name
        for a in (*p3_arts, *p4_arts)
        if a.get("sha256") and a.get("stored_path")
    }

    pdf.ln(4)
    _subsection_title(pdf, "Artefact-Level Anomaly Detail")
    _body_text(pdf,
        "The following summarises which automated checks fired for each "
        "artefact processed in Phase 5. Row counts indicate affected data rows; "
        "column lists are truncated to five entries."
    )
    pdf.ln(3)

    for cat in cat_order:
        entries = by_cat.get(cat, [])
        if not entries:
            continue

        # Category sub-header
        pdf.set_x(_MARGIN_L)
        pdf.set_font(_FONT, "B", 9)
        pdf.set_fill_color(235, 239, 250)
        pdf.cell(_USABLE_W, 5, _safe(cat.replace("_", " ").title()), fill=True, border=1)
        pdf.ln(6)

        for a in entries:
            # For image/video entries, resolve the original media filename via the
            # evidence_sha256 → P3/P4 artefact lookup; fall back to the sidecar name.
            if cat in ("images", "videos") and a.get("evidence_sha256") in _sha_to_fname:
                fname = _sha_to_fname[a["evidence_sha256"]]
            else:
                fname = Path(str(a.get("stored_path", "-"))).name
            observations: list[dict] = a.get("observations", [])

            # Collect all fired checks across observation dicts
            fired: list[str] = []
            for obs in observations:
                for key, val in obs.items():
                    if key == "database_empty" and val is True:
                        fired.append("database_empty: all tables empty")
                    elif key == "format":
                        entry_count = sum(
                            len(o.get("entries", [])) for o in observations
                        )
                        fired.append(f"format: {val}  |  entries: {entry_count}")
                    elif key == "entries":
                        pass  # handled with "format" above
                    elif key == "exif_zero_date" and val is True:
                        fired.append("exif_zero_date: EXIF timestamp is zeroed or missing")
                    elif key == "exif_missing_gps" and val is True:
                        fired.append("exif_missing_gps: no GPS coordinates in EXIF metadata")
                    elif key in ("norm_date", "norm_time", "gps_latitude", "gps_longitude"):
                        pass  # informational fields, not anomalies
                    elif key in _ROW_CHECKS and isinstance(val, list):
                        fired.append(f"{key}: {len(val)} row(s) affected")
                    elif key in _COL_CHECKS and isinstance(val, list):
                        preview = val[:5]
                        extra = len(val) - 5
                        col_str = ", ".join(preview)
                        if extra > 0:
                            col_str += f"  (+{extra} more)"
                        fired.append(f"{key}: {len(val)} column(s) - {col_str}")

            if not fired:
                continue

            # File name as bold indent label
            pdf.set_x(_MARGIN_L + 4)
            pdf.set_font(_FONT, "B", 8)
            pdf.set_text_color(50, 50, 50)
            pdf.multi_cell(_USABLE_W - 4, _LINE_H, _safe(fname))
            pdf.set_text_color(0, 0, 0)

            for line in fired:
                pdf.set_x(_MARGIN_L + 10)
                pdf.set_font(_FONT, "", 8)
                usable = _USABLE_W - 10
                pdf.cell(4, _LINE_H, "-")
                pdf.multi_cell(usable - 4, _LINE_H, _safe(line))

            pdf.ln(1)

        pdf.ln(2)


