# Layout constants

_FONT    = "Helvetica"
_MARGIN_L = 15
_MARGIN_R = 15
_MARGIN_T = 22   # extra top margin so header text never overlaps section titles
_PAGE_W   = 210  # A4 mm
_USABLE_W = _PAGE_W - _MARGIN_L - _MARGIN_R  # 180 mm
_LINE_H   = 4.5  # compact body line height


# PDF class

class _PDF(FPDF):
    def __init__(self, case_id: str) -> None:
        super().__init__(orientation="P", unit="mm", format="A4")
        self._case_id = case_id
        self.set_margins(_MARGIN_L, _MARGIN_T, _MARGIN_R)
        self.set_auto_page_break(auto=True, margin=18)

    def header(self) -> None:
        if self.page_no() == 1:
            return
        self.set_font(_FONT, "", 9)
        self.set_text_color(160, 160, 160)
        self.set_y(8)
        self.cell(0, 4, _safe(f"DFDOF Forensic Baseline Report  |  {self._case_id}"), align="R")
        self.set_text_color(0, 0, 0)
        self.set_y(_MARGIN_T)

    def footer(self) -> None:
        self.set_y(-12)
        self.set_font(_FONT, "", 7)
        self.set_text_color(160, 160, 160)
        self.cell(0, 4, f"Page {self.page_no()}  |  NOT FOR COURT USE", align="C")
        self.set_text_color(0, 0, 0)


# Public entry point

def build_report(state: State, output_path: Path, plots_dir: Path) -> None:
    """Assemble the complete PDF and write it to output_path."""
    pdf = _PDF(state.case_id)
    p7  = state.phase_outputs.get("p7_analysis_and_validation", {})

    _cover_page(pdf, state)
    _chain_of_custody(pdf, state)
    _pipeline_summary(pdf, state, p7)
    _device_identification(pdf, p7)

    p6_flights     = state.phase_outputs.get("p6_multisource_correlation", {}).get("flights", [])
    flight_analyses = p7.get("flight_analyses", [])
    fa_by_id        = {fa["flight_id"]: fa for fa in flight_analyses}

    for flight in p6_flights:
        fid = flight["flight_id"]
        fa  = fa_by_id.get(fid, {})
        _flight_section(pdf, state, flight, fa, plots_dir)

    _artefact_coverage(pdf, p7)
    _data_quality(pdf, p7, state)
    _further_investigation(pdf, p7)
    _appendix_hashes(pdf, state)
    _appendix_lineage(pdf, state)
    _appendix_tool_log(pdf, state)
    _appendix_tool_overview(pdf)

    pdf.output(str(output_path))


# Sections

def _cover_page(pdf: _PDF, state: State) -> None:
    pdf.add_page()
    pdf.ln(10)
    # Logo — centred, 40 mm wide
    logo = Path(__file__).parent.parent / "LOGO.png"
    if logo.exists():
        logo_w = 65
        pdf.image(str(logo), x=(_PAGE_W - logo_w) / 2, w=logo_w)
        pdf.ln(6)
    else:
        pdf.ln(16)
    pdf.set_font(_FONT, "B", 22)
    pdf.cell(0, 12, "Forensic Baseline Report", align="C")
    pdf.ln(8)
    pdf.set_font(_FONT, "B", 14)
    pdf.set_text_color(80, 80, 80)
    pdf.cell(0, 8, "Drone Forensic Decision and Orchestration Framework", align="C")
    pdf.set_text_color(0, 0, 0)
    pdf.ln(14)

    # Key-value metadata block — fixed column widths so everything aligns
    label_w = 48
    value_w = _USABLE_W - label_w
    rows = [
        ("Case Identifier",   state.case_id),
        ("Operator",          state.operator),
        ("Analysis Started",  (state.start_time or "")[:19].replace("T", " ")),
        ("Evidence Directory", str(state.evidence_directory or "-")),
        ("Output Directory",  str(Path(state.evidence_directory or "").parent / "dfdof_output" / state.case_id)),
        ("Evidence Sources",  str(len(state.input_evidence))),
        ("Pipeline Version",  "DFDOF v1.0 (proof of concept)"),
    ]
    for label, value in rows:
        pdf.set_x(_MARGIN_L)
        pdf.set_font(_FONT, "B", 10)
        pdf.cell(label_w, 6, _safe(label + ":"))
        pdf.set_x(_MARGIN_L + label_w)
        pdf.set_font(_FONT, "", 10)
        pdf.multi_cell(value_w, 6, _safe(value))

    pdf.ln(10)
    pdf.set_x(_MARGIN_L)
    pdf.set_font(_FONT, "I", 8)
    pdf.set_text_color(130, 130, 130)
    pdf.multi_cell(_USABLE_W, _LINE_H, _safe(
        "This report is an automated forensic baseline produced by DFDOF. "
        "It is not a court-ready expert report. All findings are bounded by the "
        "data available and must be interpreted by a qualified forensic examiner."
    ), align="C")
    pdf.set_text_color(0, 0, 0)


def _chain_of_custody(pdf: _PDF, state: State) -> None:
    pdf.add_page()
    _section_title(pdf, "1. Evidence Intake and Chain of Custody")
    _body_text(pdf,
        "The following input evidence files were ingested. SHA-256 and SHA-1 "
        "hashes were computed at intake to establish integrity baselines. "
        "No modification to original evidence files is performed by DFDOF."
    )
    pdf.ln(2)

    headers = ["File", "Classification", "Acquisition", "Size", "Hash Timestamp"]
    col_w   = [52, 32, 26, 22, 48]
    rows = []
    for ev in state.input_evidence:
        rows.append([
            Path(str(ev.source_path)).name,
            ev.source_identification or "-",
            ev.acquisition_method or "-",
            _format_size(ev.size),
            (ev.hash_timestamp or "-")[:19].replace("T", " "),
        ])
    _table(pdf, headers, rows, col_w)
    pdf.ln(4)

    # Input path
    _subsection_title(pdf, "Evidence Source Path")
    _body_text(pdf, str(state.evidence_directory or "-"))
    pdf.ln(2)

    # Full hash table — one self-contained block per file
    _subsection_title(pdf, "Cryptographic Hashes")

    row_h   = 5
    fname_w = 90   # filename column
    src_w   = 50   # classification column
    meth_w  = _USABLE_W - fname_w - src_w  # 40 mm — acquisition method
    label_w = 22   # "SHA-256:" / "SHA-1:" label column
    hash_w  = _USABLE_W - label_w  # 158 mm — wide enough for 64-char Courier 7pt

    for ev in state.input_evidence:
        fname  = Path(str(ev.source_path)).name
        source = ev.source_identification or "-"
        method = ev.acquisition_method or "-"
        sha256 = ev.sha256 or "not computed"
        sha1   = ev.sha1   or "not computed"

        # Row 1 — file metadata strip (dark-blue header): three separate columns
        pdf.set_font(_FONT, "B", 8)
        pdf.set_fill_color(50, 80, 130)
        pdf.set_text_color(255, 255, 255)
        pdf.cell(fname_w, row_h, _safe(fname),   border=1, fill=True)
        pdf.cell(src_w,   row_h, _safe(source),  border=1, fill=True)
        pdf.cell(meth_w,  row_h, _safe(method),  border=1, fill=True)
        pdf.ln()
        pdf.set_text_color(0, 0, 0)

        # Row 2 — SHA-256
        pdf.set_fill_color(250, 250, 252)
        pdf.set_font(_FONT, "B", 8)
        pdf.cell(label_w, row_h, "SHA-256:", border=1, fill=True)
        pdf.set_font("Courier", "", 7)
        pdf.cell(hash_w, row_h, _safe(sha256), border=1, fill=True)
        pdf.ln()

        # Row 3 — SHA-1
        pdf.set_fill_color(250, 250, 252)
        pdf.set_font(_FONT, "B", 8)
        pdf.cell(label_w, row_h, "SHA-1:", border=1, fill=True)
        pdf.set_font("Courier", "", 7)
        pdf.cell(hash_w, row_h, _safe(sha1), border=1, fill=True)
        pdf.ln(5)


def _pipeline_summary(pdf: _PDF, state: State, p7: dict) -> None:
    pdf.add_page()
    _section_title(pdf, "2. Pipeline Execution Summary")

    # Completed phases as numbered list
    _subsection_title(pdf, "Completed Phases")
    phases = state.completed_phases or []
    if not phases:
        _body_text(pdf, "None recorded.")
    else:
        for i, phase in enumerate(phases, 1):
            _numbered(pdf, i, phase)
    pdf.ln(4)

    # Anomaly flags
    _subsection_title(pdf, "Anomaly Flags")
    flags = state.anomaly_flags or []
    if not flags:
        _body_text(pdf, "No anomalies recorded.")
    else:
        for i, flag in enumerate(flags, 1):
            _numbered(pdf, i, flag)
    pdf.ln(4)

    # Tool status
    _subsection_title(pdf, "Tool Execution Status")
    tool_status = p7.get("tool_status", [])
    if not tool_status:
        _body_text(pdf, "No tool invocations recorded.")
    else:
        headers = ["Tool", "Invocations", "Successes", "Status"]
        col_w   = [50, 30, 30, 40]
        rows = [
            [t["tool"], str(t["invocation_count"]), str(t["success_count"]),
             _status_badge(t["status"])]
            for t in tool_status
        ]
        _table(pdf, headers, rows, col_w)


def _device_identification(pdf: _PDF, p7: dict) -> None:
    pdf.add_page()
    _section_title(pdf, "3. Device and Account Identification")

    ada = p7.get("account_and_drone_analysis", {})
    if not ada:
        _body_text(pdf, "No device or account information could be extracted.")
        return

    # Registry-driven: rows are built from _P4_IDENTITY_FIELDS plus the two P2-only keys.
    # Adding a field to a P4 field-map dict automatically appears here.
    _REPORT_FIELDS: tuple[tuple[str, str], ...] = (
        ("installed_dji_apps", "Installed DJI App(s)"),
        ("device_name",        "Controller Device"),
    ) + tuple(
        (_P4_KEY_TO_OUT_KEY.get(p4k, p4k), label)
        for p4k, label in _P4_IDENTITY_FIELDS
    )
    headers = ["Field", "Value", "Confidence", "Sources"]
    col_w   = [48, 62, 38, 22]  # sum = 170 < 180 OK
    rows = []
    for key, label in _REPORT_FIELDS:
        entry = ada.get(key)
        if not entry:
            continue
        val = entry.get("value", "-")
        if isinstance(val, list):
            val = "\n".join(str(v) for v in val)
        rows.append([
            label,
            str(val),
            _confidence_badge(entry.get("confidence", "")),
            str(len(entry.get("corroboration_sources", []))),
        ])
    if rows:
        _table(pdf, headers, rows, col_w)
    pdf.ln(4)

    _subsection_title(pdf, "Processing Coverage Score")
    cov = p7.get("coverage_score", {})
    score_items = [
        ("Evidence Sources Detected",        "evidence_sources_detected"),
        ("Artefact Categories With Data",    "artefact_categories_with_data"),
        ("Flights With Primary Correlation", "flights_with_primary_correlation"),
        ("Tools Succeeded",                  "tools_succeeded"),
    ]
    headers2 = ["Metric", "Result"]
    col_w2   = [130, 30]
    rows2 = []
    for label, key in score_items:
        v = cov.get(key, {})
        rows2.append([label, f"{v.get('value', '?')} / {v.get('total', '?')}"])
    _table(pdf, headers2, rows2, col_w2)


def _flight_section(
    pdf: _PDF,
    state: State,
    flight: dict,
    fa: dict,
    tmp_dir: Path,
) -> None:
    pdf.add_page()
    fid     = flight["flight_id"]
    corr    = flight.get("correlation", {})
    matched = corr.get("matched", False)

    _section_title(pdf, f"4. Flight Analysis - {fid.replace('_', ' ').title()}")

    # Correlation and flight window
    _subsection_title(pdf, "Correlation and Flight Window")
    status = "Matched (primary GPS+temporal)" if matched else "Unmatched (no drone log corroboration)"
    _kv(pdf, "Status", status)
    if matched:
        _kv(pdf, "Confidence",          str(corr.get("confidence", "-")))
        _kv(pdf, "GPS Overlap",         f"{corr.get('overlap_s', '-')} s")
        _kv(pdf, "Median GPS Distance", f"{corr.get('median_distance_m', '-')} m")
        _raw = corr.get("overlap_fraction")
        _overlap_pct = f"{int(_raw * 100)}%" if isinstance(_raw, (int, float)) else "-"
        _kv(pdf, "Overlap",             _overlap_pct)
        _mr = corr.get("match_rate")
        _mr_pct = f"{int(_mr * 100)}%" if isinstance(_mr, (int, float)) else "-"
        _kv(pdf, "GPS Match Rate",      _mr_pct)

    # Build sha → category lookup from P5 normalised artefacts
    _p5_artefacts = (
        state.phase_outputs
        .get("p5_normalisation_and_anomaly_checking", {})
        .get("normalised_artefacts", [])
    )
    _sha_to_cat = {a.get("sha256", ""): a.get("artefact_category", "") for a in _p5_artefacts}
    _sha_to_source = {a.get("sha256", ""): a.get("source_identification", "-") for a in _p5_artefacts}

    _cat_labels = {
        FLIGHT_RECORDS: "Flight Record",
        DRONE_LOGS:     "Drone Log",
    }

    fi = flight.get("flights_identified", [])
    for seg in fi:
        sha = seg.get("evidence_sha256") or "-"
        cat = _sha_to_cat.get(sha, "")
        label = _cat_labels.get(cat, "Source")
        _kv_hash(pdf, f"{label} SHA-256", sha)
        _kv(pdf, "Start",    seg.get("start", "-"))
        _kv(pdf, "End",      seg.get("end",   "-"))
        _kv(pdf, "Duration", f"{seg.get('duration_s', '-')} s")
    pdf.ln(3)

    # Flight metrics
    if fa:
        _subsection_title(pdf, "Flight Metrics")
        _kv(pdf, "Peak Height",        f"{fa.get('peak_height_m')} m" if fa.get('peak_height_m') else "-")
        _kv(pdf, "Distance Travelled", f"{fa.get('distance_travelled')} m" if fa.get('distance_travelled') else "-")
        _kv(pdf, "Video Recording",    "Yes" if fa.get("video_taken") else "No")
        _kv(pdf, "Photo Capture",      "Yes" if fa.get("photo_taken") else "No")
        if fa.get("number_photos_taken") is not None:
            _kv(pdf, "Photos Taken",      str(fa["number_photos_taken"]))
        if fa.get("duration_recording") is not None:
            _kv(pdf, "Recording Duration", f"{fa['duration_recording']} s")
        if fa.get("flight_record_complete") is not None:
            complete = "Yes" if fa["flight_record_complete"] else "No - drone had not returned to home point"
            _kv(pdf, "Record Complete", complete)
        pdf.ln(3)

    # Key events table
    tl_path = flight.get("stored_path", "")
    events  = _load_timeline_events(tl_path)

    key_event_types = {
        "Log started", "Log ended", "Motor turned on", "Motor turned off",
        "Reached peak height", "Record mode changed",
    }
    photo_events = [
        e for e in events
        if e.get("event") == "Photo mode changed"
        and str(e.get("data", {}).get("photo_mode", "No")).lower() not in ("no", "")
    ]
    key_events = [e for e in events if e.get("event") in key_event_types] + photo_events

    # Fly modes — numbered chronological list
    modes_seen: list[str] = []
    seen_set:   set[str]  = set()
    for e in events:
        if e.get("event") == "Fly mode changed":
            m = e.get("data", {}).get("fly_mode", "")
            if m and m not in seen_set:
                modes_seen.append(m)
                seen_set.add(m)
    if modes_seen:
        _subsection_title(pdf, "Fly Modes Observed (Chronological)")
        for i, mode in enumerate(modes_seen, 1):
            _numbered(pdf, i, mode)
        pdf.ln(3)

    if key_events:
        _subsection_title(pdf, "Key Events")
        headers = ["Timestamp (UTC)", "Source", "Event", "Details"]
        col_w   = [40, 35, 35, 60]
        rows = []
        for ev in key_events:
            ts  = (ev.get("timestamp") or "-")[:19].replace("T", " ")
            src = _short_source(ev.get("source", ""))
            evt = ev.get("event", "")
            det = _event_detail(ev)
            rows.append([ts, src, evt, det])
        _table(pdf, headers, rows, col_w)
    else:
        _body_text(pdf, "No key events extracted from timeline.")
    pdf.ln(3)

    # Warnings
    warnings = [
        e for e in events
        if e.get("event") == "Log message"
        and "Warning" in str(e.get("data", {}).get("log_message", ""))
    ]
    if warnings:
        _subsection_title(pdf, "In-Flight Warnings")
        headers = ["Timestamp (UTC)", "Source", "Warning Message"]
        col_w   = [40, 35, 95]
        rows = []
        for ev in warnings[:30]:
            ts  = (ev.get("timestamp") or "-")[:19].replace("T", " ")
            src = _short_source(ev.get("source", ""))
            msg = str(ev.get("data", {}).get("log_message", ""))[:160]
            rows.append([ts, src, msg])
        _table(pdf, headers, rows, col_w)
        pdf.ln(3)

    # Correlation tables
    plausible = flight.get("plausibly_correlated", [])
    possible  = flight.get("possibly_correlated",  [])
    if plausible or possible:
        _subsection_title(pdf, "Correlated Artefacts")
        if plausible:
            _body_text(pdf, "Plausibly correlated (timestamp within flight window):")
            rows = []
            for ptr in plausible:
                sha = ptr.removeprefix("p5:").removeprefix("p4:")
                source = _sha_to_source.get(sha, "-")
                rows.append([_safe(source), _safe(ptr)])
            _table(pdf, ["Source", "Pointer"], rows, [60, 120])
        if possible:
            _body_text(pdf, "Possibly correlated (indirect indicators):")
            for pc in possible:
                source  = _safe(str(pc.get("source", "-")))
                basis   = _safe(_format_basis(pc.get("data", {})))
                pointer = _safe(str(pc.get("source_pointer", "-")))
                _corr_row(pdf, [source, basis], [60, 120], (50, 80, 130),
                          text_rgb=(255, 255, 255), bold=True)
                _corr_row(pdf, [pointer],       [180],     (255, 255, 255))
                pdf.ln(2)
        pdf.ln(3)

    # ── Sensor plots — each on its own page ──────────────────────────────────
    fr_csv, dl_csv = _flight_csv_paths(state, flight)

    fr_png = plot_flight_record(fr_csv, events, fid, tmp_dir) if fr_csv else None
    dl_png = plot_drone_log(dl_csv, fid, tmp_dir)             if dl_csv else None

    if fr_png:
        pdf.add_page()
        _subsection_title(pdf, "Flight Record - Sensor Telemetry")
        _embed_image(pdf, fr_png, w=175)
        pdf.ln(2)
        pdf.set_font(_FONT, "I", 7)
        pdf.set_text_color(120, 120, 120)
        pdf.multi_cell(_USABLE_W, _LINE_H, _safe(
            "GPS coordinates are derived from the drone's onboard receiver and represent "
            "sensor-recorded positions, not independently verified measurements. "
            "A satellite count of 10 or more is associated with good horizontal precision "
            "(approximately 1.5-3 m); counts below 4 indicate a poor fix with significantly "
            "reduced positional reliability, and those rows are flagged in this report. "
            "Low satellite counts may affect the accuracy of the flight path, ground track, "
            "and any location-based conclusions drawn from this record."
        ))
        pdf.set_text_color(0, 0, 0)
    elif not fr_csv:
        pass  # no flight record available — silent
    else:
        _body_text(pdf, "Flight record sensor plots not available.")

    if dl_png:
        pdf.add_page()
        _subsection_title(pdf, "Drone Log - Sensor Telemetry")
        _embed_image(pdf, dl_png, w=175)
        pdf.ln(2)
        pdf.set_font(_FONT, "I", 7)
        pdf.set_text_color(120, 120, 120)
        pdf.multi_cell(_USABLE_W, _LINE_H, _safe(
            "GPS coordinates are derived from the drone's onboard receiver; horizontal accuracy "
            "is subject to satellite geometry (hDOP) and signal environment, with DJI manufacturer "
            "specification of +/-1.5 m horizontal in GPS mode. "
            "An hDOP below 1.5 is considered very precise, while values above 5.0 indicate "
            "degraded positional accuracy - those records are flagged and should be treated with "
            "reduced confidence in derived locations and ground track. "
            "Bayesian likelihood ratio analysis for a specific location hypothesis is possible "
            "using a Gaussian error model parameterised by hDOP, but requires case-specific "
            "inputs and is outside the scope of this baseline report."
        ))
        pdf.set_text_color(0, 0, 0)

    # ── Flight track ──────────────────────────────────────────────────────────
    kml       = _find_kml_path(state)
    track_png = None
    if fr_csv or dl_csv:
        track_png = plot_flight_track(fr_csv, dl_csv, kml, fid, tmp_dir)
    if track_png:
        pdf.add_page()
        _subsection_title(pdf, "Flight Ground Track")
        # Constrain by height so tall stacked plots stay on one page with the header.
        # A4 usable height minus top margin, subsection title, and caption ≈ 220 mm.
        _track_max_h = 220
        _track_w     = int(_USABLE_W * 0.80)   # 20 % smaller than full usable width
        try:
            x = (_PAGE_W - _track_w) / 2
            pdf.image(str(track_png), x=x, w=_track_w, h=_track_max_h)
        except Exception:
            _body_text(pdf, "[Flight track image could not be embedded.]")
        pdf.ln(2)
        pdf.set_font(_FONT, "I", 7)
        pdf.set_text_color(120, 120, 120)
        pdf.cell(0, 4, "Coordinates are WGS84. No base map. Colour represents relative height (metres).")
        pdf.ln(4)
        if kml and kml.exists():
            pdf.set_font(_FONT, "I", 7)
            pdf.set_text_color(120, 120, 120)
            pdf.multi_cell(_USABLE_W, _LINE_H, _safe(
                f"A KML file ({kml.name}) is available in the output directory and may be loaded into "
                "Google Earth Pro for 3D visualisation of the flight path. Note: loading this file into "
                "an external application constitutes forensic evidence disclosure — ensure this is "
                "authorised before doing so."
            ))
        pdf.set_text_color(0, 0, 0)
    else:
        _body_text(pdf, "Flight track plot not available.")


def _artefact_coverage(pdf: _PDF, p7: dict) -> None:
    pdf.add_page()
    _section_title(pdf, "5. Artefact Coverage")

    _subsection_title(pdf, "Source Coverage")
    sc = p7.get("source_coverage", [])
    if sc:
        headers = ["Source", "Detected"]
        col_w   = [120, 40]
        rows = [[s["source"], "Yes" if s["detected"] else "No"] for s in sc]
        _table(pdf, headers, rows, col_w)
    pdf.ln(4)

    _subsection_title(pdf, "Artefact Counts per Source and Category")
    per_src = p7.get("artefact_coverage_per_source", [])
    if per_src:
        all_cats = list(CONTROLLER_ARTEFACT_CATEGORIES)
        src_col_w = 30
        num_w = max(21, int((_USABLE_W - src_col_w) / len(all_cats)))
        headers = ["Source"] + [c.replace("_", " ").title() for c in all_cats]
        col_w   = [src_col_w] + [num_w] * len(all_cats)
        rows = []
        for src_entry in per_src:
            cat_counts = {a["category"]: a["count"] for a in src_entry.get("artefacts", [])}
            rows.append(
                [src_entry["source"]] + [str(cat_counts.get(c, 0)) for c in all_cats]
            )
        _table(pdf, headers, rows, col_w)
    pdf.ln(4)

    _subsection_title(pdf, "Data Quality Notes per Category")
    ac = p7.get("artefact_coverage", [])
    for entry in ac:
        notes = entry.get("notes", [])
