def _hash_block(pdf: _PDF, artefact: dict) -> None:
    """Render one artefact as a 3-row block: metadata strip + SHA-256 + SHA-1.

    All rows span the full usable page width (180 mm) so the complete hash
    values are never truncated.
    """
    fname    = Path(str(artefact.get("stored_path", "-"))).name
    category = (artefact.get("artefact_category") or "-").replace("_", " ").title()
    source   = artefact.get("source_identification") or "-"
    method   = artefact.get("acquisition_method") or "-"
    sha256   = artefact.get("sha256") or "not computed"
    sha1     = artefact.get("sha1")   or "not computed"

    # All three rows use the same fixed height so they are visually identical.
    row_h = 5

    # Row 1 — metadata strip (shaded): file | category | source | method
    pdf.set_font(_FONT, "B", 8)
    pdf.set_fill_color(225, 230, 245)
    pdf.cell(62, row_h, _safe(fname[:55]),  border=1, fill=True)
    pdf.cell(40, row_h, _safe(category),   border=1, fill=True)
    pdf.cell(40, row_h, _safe(source),     border=1, fill=True)
    pdf.cell(38, row_h, _safe(method),     border=1, fill=True)
    pdf.ln()

    # Row 2 — SHA-256
    pdf.set_fill_color(250, 250, 252)
    pdf.set_font(_FONT, "B", 7)
    pdf.cell(20, row_h, "SHA-256:", border=1, fill=True)
    pdf.set_font("Courier", "", 7)
    pdf.cell(160, row_h, _safe(sha256), border=1, fill=True)
    pdf.ln()

    # Row 3 — SHA-1
    pdf.set_fill_color(250, 250, 252)
    pdf.set_font(_FONT, "B", 7)
    pdf.cell(20, row_h, "SHA-1:", border=1, fill=True)
    pdf.set_font("Courier", "", 7)
    pdf.cell(160, row_h, _safe(sha1), border=1, fill=True)
    pdf.ln()
    pdf.ln(4)  # inter-block gap


