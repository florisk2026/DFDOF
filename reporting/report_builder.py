def _flight_csv_paths(
    state: State, flight: dict
) -> tuple[Path | None, Path | None]:
    p5_artefacts = (
        state.phase_outputs
        .get("p5_normalisation_and_anomaly_checking", {})
        .get("normalised_artefacts", [])
    )
    sha_to_norm = {a.get("sha256", ""): a for a in p5_artefacts}

    fr_csv: Path | None = None
    dl_csv: Path | None = None
    for seg in flight.get("flights_identified", []):
        a = sha_to_norm.get(seg.get("evidence_sha256", ""))
        if not a:
            continue
        sp = a.get("stored_path")
        if not sp:
            continue
        p = Path(sp)
        if not p.exists():
            continue
        cat = a.get("artefact_category")
        if cat == FLIGHT_RECORDS:
            fr_csv = p
        elif cat == DRONE_LOGS:
            dl_csv = p
    return fr_csv, dl_csv


