def _event_detail(ev: dict) -> str:
    data  = ev.get("data", {})
    event = ev.get("event", "")
    if event == "Log started":
        parts = []
        if data.get("serial_drone"):
            parts.append(f"SN: {data['serial_drone']}")
        if data.get("dji_app_version"):
            parts.append(f"App: {data['dji_app_version']}")
        if data.get("name_drone"):
            parts.append(data["name_drone"])
        return "; ".join(parts)[:80]
    if event == "Log ended":
        parts = []
        if data.get("distance_to_homepoint") is not None:
            parts.append(f"Dist home: {data['distance_to_homepoint']:.1f} m")
        if data.get("height") is not None:
            parts.append(f"Height: {data['height']:.1f} m")
        if data.get("duration_recording") is not None:
            parts.append(f"Rec: {data['duration_recording']} s")
        return "; ".join(parts)[:80]
    if event == "Reached peak height":
        h = data.get("relative_height")
        return f"{h:.1f} m" if h is not None else "-"
    if event in ("Record mode changed", "Photo mode changed"):
        mode = data.get("record_mode") or data.get("photo_mode") or "-"
        return str(mode)[:40]
    if "motor_state" in data:
        return data["motor_state"]
    return ""


